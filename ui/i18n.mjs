export const SUPPORTED_LANGUAGES = Object.freeze(Object.keys(messages));
export function resolveLanguage(locale) {
  const language =
    typeof locale === "string"
      ? locale.trim().toLowerCase().split(/[-_]/)[0]
      : "";
  return SUPPORTED_LANGUAGES.includes(language) ? language : "es";
}
export function createTranslator(locale) {
  const values = messages[resolveLanguage(locale)];
  const dictionary = {};
  keys.forEach((key, index) => {
    dictionary[key] = values[index] || messages.es[index];
  });
  return (key) => dictionary[key] || key;
}
// Same read-only locale used by ShellUI's I18nPS; never changes the console language.
export function readSystemLocale(baseRequire) {
  try {
    return baseRequire.c["bX5JscBE"].exports.StringResource.defaultLocale;
  } catch {
    return undefined;
  }
}
